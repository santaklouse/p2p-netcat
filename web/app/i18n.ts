export function getPageLanguage(): Language {
  if (typeof window === "undefined") return "en";
  return new URLSearchParams(window.location.search).get("lang") === "ru" ? "ru" : "en";
}

export function getLanguageUrl(language: Language) {
  if (typeof window === "undefined") return language === "ru" ? "?lang=ru" : ".";
  const url = new URL(window.location.href);
  if (language === "ru") url.searchParams.set("lang", "ru");
  else url.searchParams.delete("lang");
  return `${url.pathname}${url.search}${url.hash}`;
}
